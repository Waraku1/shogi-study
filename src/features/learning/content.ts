export const vocabularyCards: readonly LearningItem[] = vocabulary.map(
  ([word, definition, example], i) => {
    const correctIndex = i % 3;
    const options = [
      vocabulary[(i + 7) % vocabulary.length][1],
      vocabulary[(i + 19) % vocabulary.length][1],
    ];
    options.splice(correctIndex, 0, definition);
    return {
      id: `vocab-${word}`,
      contentVersion: CONTENT_VERSION,
      subject: "Vocabulary",
      difficulty: i < 50 ? "High school" : "University",
      title: word,
      prompt: `What does “${word}” mean in academic English?`,
      answer: definition,
      example,
      quiz: {
        question: `Choose the definition of “${word}”.`,
        options,
        correctIndex,
      },
    };
  },
);
